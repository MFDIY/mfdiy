import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

/**
 * Writes `src/components/Icon/paths.ts` from Material Symbols, Sharp, weight 300 (0022). Add a name
 * from https://fonts.google.com/icons here and run `npm run icons -w @mfdiy/ui`.
 */
const names = [
  'add',
  'check',
  'chevron_left',
  'chevron_right',
  'close',
  'content_copy',
  'content_paste',
  'delete',
  'edit',
  'fit_screen',
  'fullscreen',
  'info',
  'keyboard_arrow_down',
  'keyboard_arrow_up',
  'light_mode',
  'list_arrow',
  'menu',
  'more_horiz',
  'redo',
  'remove',
  'undo',
  'unfold_more',
  'warning',
  'zoom_in',
  'zoom_out'
] as const;

const require = createRequire(import.meta.url);
const symbols = join(dirname(require.resolve('@material-symbols/svg-300/package.json')), 'sharp');
const { version } = JSON.parse(readFileSync(require.resolve('@material-symbols/svg-300/package.json'), 'utf8')) as {
  version: string;
};

const entries = [...names].sort().map(name => {
  const svg = readFileSync(join(symbols, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map(match => match[1]);

  if (paths.length !== 1) {
    throw new Error(`${name}: expected one path, found ${paths.length}`);
  }

  return `  ${name}: '${paths[0]}'`;
});

const output = `// Generated by scripts/generate-icons.ts from @material-symbols/svg-300 ${version} (Sharp). Don't edit.
// Material Symbols © Google, Apache License 2.0: https://github.com/google/material-design-icons

/** Each icon's path, drawn in a \`0 -960 960 960\` view box. */
export const paths = {
${entries.join(',\n')}
} as const;
`;

writeFileSync(join(import.meta.dirname, '../src/components/Icon/paths.ts'), output);
console.log(`Wrote ${entries.length} icons.`);
